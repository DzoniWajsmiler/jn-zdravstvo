import sys, pandas as pd, warnings
warnings.filterwarnings("ignore")
df = pd.read_excel(sys.argv[1], header=0)
print(df.shape)
df["d"] = pd.to_datetime(df["Datum oddaje naročila"], format="%d.%m.%Y", errors="coerce")
print(df["d"].min(), df["d"].max(), df["d"].isna().sum())
print(df.groupby(df["d"].dt.year)["Vrednost brez DDV"].agg(["count","sum"]))
print("\nCPV šifra top:\n", df["CPV šifra"].astype(str).str[:5].value_counts().head(10))
print("\nPredmet:\n", df["Predmet naročila"].value_counts())
print("\nVrsta postopka:\n", df["Vrsta postopka"].value_counts())
print("\nZakon:\n", df["Zakon"].value_counts())
print("\nNaročnik top by value:\n", df.groupby("Naročnik")["Vrednost brez DDV"].agg(["count","sum"]).sort_values("sum",ascending=False).head(15))
print("\nIzvajalec top by value:\n", df.groupby("Izvajalec")["Vrednost brez DDV"].agg(["count","sum"]).sort_values("sum",ascending=False).head(10))
print("\nNull counts:\n", df.isna().sum())
print("\nVrednost describe:\n", df["Vrednost brez DDV"].describe())
print("dup rows:", df.duplicated().sum(), " dup (objava,izvajalec,vrednost):", df.duplicated(["Številka objave na PJN","Izvajalec","Vrednost brez DDV"]).sum())
